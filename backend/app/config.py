"""
Central settings object - the Python equivalent of reading `process.env.*`
scattered across the old Node codebase. Every other module imports `settings`
from here instead of touching os.environ directly.
"""
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", extra="ignore")

    PORT: int = 5000
    MONGO_URI: str = "mongodb://localhost:27017/intellitwin"
    JWT_SECRET: str = "replace_this_with_a_long_random_secret"
    JWT_EXPIRES_IN_DAYS: int = 7
    CLIENT_ORIGIN: str = "http://localhost:3000"

    ANTHROPIC_API_KEY: str = ""
    ANTHROPIC_MODEL: str = "claude-sonnet-4-6"

    # Which model actually does generation for every agent (Echo's
    # extraction, Atlas, Compass, Nova, Collaborate) - "ollama" (default: free,
    # runs locally, serves Llama 3.2 through Ollama's OpenAI-compatible API),
    # "openai" (paid, hosted) or "anthropic" (Claude). For "ollama" see
    # OLLAMA_BASE_URL/OLLAMA_MODEL below. Switching this does NOT
    # touch embeddings (see OPENAI_EMBEDDING_MODEL below) - that's a
    # separate, independent choice. If the selected provider's API key
    # isn't set (n/a for ollama, which needs no key), agents fall back to
    # the same offline placeholder response used when no key is configured
    # at all - see app/llm.py.
    LLM_PROVIDER: str = "ollama"

    # Echo's memory layer (Phase 3). Embeddings power semantic search over
    # memory_entries. OPENAI_API_KEY is optional - Echo works fully offline
    # with a deterministic local embedding, just with lower recall quality,
    # same "always demoable" philosophy as app/llm.py's fallback. This same
    # key is reused for generation if LLM_PROVIDER=openai (above) - it's one
    # OpenAI account either way, just two independent settings for what it's
    # used for.
    OPENAI_API_KEY: str = ""
    OPENAI_EMBEDDING_MODEL: str = "text-embedding-3-small"
    OPENAI_MODEL: str = "gpt-4o"
    EMBEDDING_DIM: int = 512

    # Free, local generation via Ollama (https://ollama.com) - install it,
    # `ollama pull llama3.2` (or another tool-calling-capable model), run
    # `ollama serve` (usually starts automatically). LLM_PROVIDER=ollama is
    # the default. No API key needed - it's your own
    # machine. Ollama exposes an OpenAI-compatible endpoint, so this reuses
    # the same request/response handling as the "openai" provider in
    # app/llm.py, just pointed at a different base_url with no key.
    OLLAMA_BASE_URL: str = "http://localhost:11434/v1"
    OLLAMA_MODEL: str = "llama3.2"
    # Local models can be slow on CPU, especially on the first request while
    # Ollama loads the weights into memory.
    OLLAMA_TIMEOUT_SECONDS: float = 180.0
    # Sampling temperature for local generation; llama3.2 is a small model and
    # follows tool-call formats more reliably at a low temperature.
    OLLAMA_TEMPERATURE: float = 0.3

    # Which local account the standalone Echo MCP server acts as (see
    # app/mcp/echo_server.py) - MCP servers run outside the JWT/request
    # flow, so this is how it knows whose memory to read/write.
    ECHO_MCP_USER_EMAIL: str = ""

    # Phase 5 - Atlas's search_web tool (app/tools/web.py). Optional; Atlas
    # falls back to a clearly-labeled "web search not configured" note
    # without it, same offline-safe pattern as the LLM/embedding fallbacks.
    TAVILY_API_KEY: str = ""

    # Compass AI next-action suggestions (app/ai_suggestions.py). Generated by the
    # active LLM from the user's stored tasks/goals/events, cached per user, and
    # always labelled as AI. The rule-based suggestions keep working without it.
    AI_SUGGESTIONS_ENABLED: bool = True
    AI_SUGGESTIONS_TIMEOUT_SECONDS: float = 90.0
    # After a failed generation for unchanged data, wait this long before retrying.
    AI_SUGGESTIONS_FAILURE_COOLDOWN_SECONDS: int = 600

    # Phase 5 - the agentic tool-use loop's safety valve (app/llm.py's
    # call_llm_with_tools): max request/response round trips with Claude
    # before we stop letting it call more tools and force a final answer.
    AGENT_MAX_TOOL_TURNS: int = 6

    # Post-rating improvement - if the *same* tool fails this many times in
    # a row (not just any tool, the same one), the loop stops calling tools
    # early instead of burning the rest of AGENT_MAX_TOOL_TURNS retrying
    # something that isn't going to start working.
    AGENT_MAX_CONSECUTIVE_TOOL_FAILURES: int = 2


settings = Settings()
